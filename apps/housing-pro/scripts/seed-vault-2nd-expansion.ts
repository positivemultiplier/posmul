function formatYamlArray(items: string[]): string {
  return `[${items.map((x) => `"${x.replace(/"/g, '\\"')}"`).join(", ")}]`;
}

function buildMarkdown(s: VaultConceptSeed): string {
  const lines: string[] = [
    "---",
    `id: ${s.id}`,
    `title: "${s.title}"`,
    ...(s.englishTitle ? [`english_title: "${s.englishTitle}"`] : []),
    `aliases: ${formatYamlArray(s.aliases)}`,
    `exam_stage: "${s.examStage}"`,
    `subject: "${s.subject}"`,
    `chapter_code: "${s.chapterCode}"`,
    `category: "${s.category}"`,
    `tags: ${formatYamlArray(s.tags)}`,
    ...(s.contrastAxisId ? [`contrast_axis_id: "${s.contrastAxisId}"`] : []),
    ...(s.contrastSide ? [`contrast_side: "${s.contrastSide}"`] : []),
    `same_group_ids: ${formatYamlArray(s.sameGroupIds)}`,
    `contrast_ids: ${formatYamlArray(s.contrastIds)}`,
    `db_search_keyword: "${s.dbSearchKeyword}"`,
    ...(s.lawRef ? [`law_ref: "${s.lawRef}"`] : []),
    "---",
    "",
    `# ${s.title}`,
    "",
    "## 핵심 특징",
    ...s.summaryBullets.map((b) => `- ${b}`),
    "",
    "## 기출 함정",
    `- ${s.trapWarning}`,
    "",
  ];

  if (s.proFieldTip) {
    lines.push("## 소장Pro 실무 팁", `- ${s.proFieldTip}`, "");
  }

  return lines.join("\n");
}

function main() {
  const vaultRoot = path.resolve(process.cwd(), "content", "vault", "housing");
  let count = 0;

  for (const seed of EXPANSION_SEEDS) {
    const dir = path.join(vaultRoot, ...seed.folder.split("/"));
    fs.mkdirSync(dir, { recursive: true });
    const filePath = path.join(dir, `${seed.id}.md`);
    fs.writeFileSync(filePath, buildMarkdown(seed), "utf-8");
    count += 1;
  }

  console.log(`✅ 2차 MVP 확장 시드 생성 완료: +${count}개 개념 노드`);
}

main();
